import itertools


def solve_logic_table():
    # ==========================================
    # НАСТРОЙКИ (Вводите данные здесь)
    # ==========================================

    # 1. Логическое выражение.
    # Замените логические операторы на язык Python:
    # ∧ -> and
    # ∨ -> or
    # ¬ -> not
    # ≡ (эквиваленция) -> ==
    # → (импликация) -> (not A) or B  ИЛИ  A <= B (в Python это работает так же)
    # ⊕ (исключающее или) -> !=

    expression = "x or z and (y <= ( w and not z))"

    # 2. Переменные (столбцы таблицы без учета F).
    # Обычно это x, y, z, w. Порядок не важен, скрипт переберет все комбинации.
    variables = ['x', 'y', 'z', 'w']

    # 3. Таблица истинности.
    # Указываем только те строки, где есть хоть какое-то значение.
    # None или '' означают "пустая ячейка" (значение неизвестно).
    # Последний элемент в списке - это значение F.

    table_data = [
        # [col1, col2, col3, col4, F]
        [None, None, 0, 0, 0],
        [None, 0, 0, 0, 0],
        [None, 0, 0, None, 0],
        [None, None, None, 0, 0],
        [None, None, 0, None, 0]
    ]

    # ==========================================
    # ЛОГИКА РЕШЕНИЯ
    # ==========================================

    print(f"Ищу соответствие для выражения: {expression}")
    print(f"Столбцы таблицы (неизвестные): {variables}")
    print("-" * 50)

    # Перебираем все возможные перестановки переменных (например, xyzw, xzyw...)
    # Это имитирует все варианты того, какая буква какому столбцу соответствует
    for perm in itertools.permutations(variables):
        # perm - это кортеж, например ('z', 'w', 'x', 'y')
        # Создаем словарь для подстановки: переменная -> значение из столбца
        is_match = True

        for row in table_data:
            # Получаем значения переменных для текущей строки согласно перестановке
            # row[:-1] это столбцы x,y,z,w; row[-1] это F

            # Подготавливаем локальные переменные для eval()
            # Сопоставляем: perm[0] = row[0], perm[1] = row[1] ...
            local_vars = {}
            valid_row = True

            for i, var_name in enumerate(perm):
                val = row[i]
                if val is None:
                    # Если ячейка пустая, мы не можем проверить эту строку точно,
                    # но в задачах ЕГЭ обычно пустые ячейки не дают противоречий.
                    # Мы проверяем только те строки, где все 4 переменные заполнены?
                    # НЕТ! В задании 2 часто даны частичные строки.
                    # Стратегия: мы должны проверить, не приводит ли данная расстановка
                    # к тому, что F должен быть 1, а в таблице стоит 0 (или наоборот).
                    # Если ячейка пустая, мы считаем, что условие не нарушено этой ячейкой,
                    # но мы должны вычислить F для полного набора.

                    # Однако, в данном конкретном задании нам даны фрагменты строк.
                    # Мы не можем вычислить F, если не знаем все переменные.
                    # Значит, мы ищем перестановку, при которой СУЩЕСТВУЮТ такие наборы переменных,
                    # которые дают указанные в таблице значения F.

                    # Упрощенный подход для Задания 2:
                    # Мы берем строку таблицы. Подставляем значения в переменные.
                    # Если значение переменной неизвестно (None), мы не можем проверить строку полностью.
                    # Но! В таблице даны "неповторяющиеся строки".
                    # Обычно достаточно найти перестановку, где вычисленные значения F
                    # для ПОЛНОСТЬЮ заполненных строк совпадают с табличными F.
                    # А для частично заполненных - мы просто игнорируем их проверку или
                    # проверяем, что вычисленное F не противоречит табличному (если F известно).

                    # В данном скрипте реализуем строгую проверку:
                    # Если переменная None, пропускаем проверку этой строки (считаем, что она совместима).
                    # Если все переменные известны, проверяем F.
                    pass

                local_vars[var_name] = val

            # Если есть хоть одна None, мы не можем точно вычислить выражение для этой строки
            # (если только выражение не упрощается, но Python eval требует всех переменных).
            if any(v is None for v in local_vars.values()):
                continue

            try:
                # Вычисляем выражение
                # В Python False=0, True=1. Для вывода часто нужны 0/1, но для логики подходят bool
                res = eval(expression, {"__builtins__": None}, local_vars)
                # Приводим к 0/1
                res_int = 1 if res else 0

                table_f = row[-1]

                if table_f is not None and res_int != table_f:
                    is_match = False
                    break  # Эта перестановка не подходит
            except Exception:
                is_match = False
                break

        if is_match:
            print(f"НАЙДЕНО РЕШЕНИЕ!")
            print(f"Столбцы таблицы (слева направо): {perm}")
            print(f"Ответ: {''.join(perm).lower()}")
            return

    print("Решение не найдено. Проверьте данные.")


# Запуск
if __name__ == "__main__":
    solve_logic_table()